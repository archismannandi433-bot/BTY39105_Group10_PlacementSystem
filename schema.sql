DROP TABLE IF EXISTS APPLICATION;
DROP TABLE IF EXISTS JOB_ELIGIBILITY;
DROP TABLE IF EXISTS JOB;
DROP TABLE IF EXISTS COMPANY;
DROP TABLE IF EXISTS ACADEMIC_RECORD;
DROP TABLE IF EXISTS STUDENT;
DROP TABLE IF EXISTS PROGRAM;
DROP TABLE IF EXISTS USERS;

CREATE TABLE USERS (
    user_id INTEGER PRIMARY KEY AUTOINCREMENT,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK(role IN ('STUDENT', 'COMPANY', 'ADMIN'))
);

CREATE TABLE PROGRAM (
    program_id INTEGER PRIMARY KEY AUTOINCREMENT,
    program_name TEXT NOT NULL,
    department TEXT NOT NULL
);

CREATE TABLE STUDENT (
    student_id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER UNIQUE NOT NULL,
    student_code TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    phone TEXT NOT NULL,
    program_id INTEGER,
    FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE,
    FOREIGN KEY (program_id) REFERENCES PROGRAM(program_id)
);

CREATE TABLE ACADEMIC_RECORD (
    record_id INTEGER PRIMARY KEY AUTOINCREMENT,
    student_id INTEGER UNIQUE NOT NULL,
    cgpa REAL NOT NULL,
    active_backlogs INTEGER DEFAULT 0,
    tenth_percentage REAL NOT NULL,
    twelfth_percentage REAL NOT NULL,
    FOREIGN KEY (student_id) REFERENCES STUDENT(student_id) ON DELETE CASCADE
);

CREATE TABLE COMPANY (
    company_id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER UNIQUE NOT NULL,
    company_name TEXT NOT NULL,
    industry TEXT NOT NULL,
    contact_email TEXT UNIQUE NOT NULL,
    location TEXT NOT NULL,
    FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE
);

CREATE TABLE JOB (
    job_id INTEGER PRIMARY KEY AUTOINCREMENT,
    company_id INTEGER NOT NULL,
    job_title TEXT NOT NULL,
    job_description TEXT,
    package_lpa REAL NOT NULL,
    drive_date DATE NOT NULL,
    FOREIGN KEY (company_id) REFERENCES COMPANY(company_id) ON DELETE CASCADE
);

CREATE TABLE JOB_ELIGIBILITY (
    eligibility_id INTEGER PRIMARY KEY AUTOINCREMENT,
    job_id INTEGER UNIQUE NOT NULL,
    min_cgpa REAL DEFAULT 0.0,
    max_backlogs_allowed INTEGER DEFAULT 0,
    FOREIGN KEY (job_id) REFERENCES JOB(job_id) ON DELETE CASCADE
);

CREATE TABLE APPLICATION (
    app_id INTEGER PRIMARY KEY AUTOINCREMENT,
    student_id INTEGER NOT NULL,
    job_id INTEGER NOT NULL,
    application_date DATE DEFAULT (CURRENT_DATE),
    status TEXT DEFAULT 'APPLIED' CHECK(status IN ('APPLIED', 'SHORTLISTED', 'OFFERED', 'REJECTED')),
    FOREIGN KEY (student_id) REFERENCES STUDENT(student_id) ON DELETE CASCADE,
    FOREIGN KEY (job_id) REFERENCES JOB(job_id) ON DELETE CASCADE,
    UNIQUE(student_id, job_id)
);